#!/usr/bin/env python3
"""Embed game assets into C source so the final binary is self-contained.

Usage: embed_assets.py <assets_dir> <output_dir>

- PNG files (8-bit RGBA, non-interlaced) are decoded to raw RGBA pixels and
  exposed as EmbeddedImage entries.
- Fonts and sounds (.ttf, .otf, .wav, .ogg) are exposed as raw EmbeddedBlob
  entries; anything else is ignored.

Asset names are their path relative to <assets_dir> without extension,
for example "sprites/zombies/riot/walk" or "fonts/DejaVuSansMono".
Only the Python standard library is used.
"""
from __future__ import annotations

import struct
import sys
import zlib
from pathlib import Path

PNG_SIGNATURE = b'\x89PNG\r\n\x1a\n'
IMAGE_EXTENSIONS = {'.png'}
BLOB_EXTENSIONS = {'.ttf', '.otf', '.wav', '.ogg'}


def decode_png_rgba(path: Path) -> tuple[int, int, bytes]:
    data = path.read_bytes()
    if data[:8] != PNG_SIGNATURE:
        raise ValueError(f'{path}: not a PNG file')
    pos = 8
    width = height = 0
    idat = bytearray()
    while pos < len(data):
        length, kind = struct.unpack('>I4s', data[pos:pos + 8])
        chunk = data[pos + 8:pos + 8 + length]
        pos += 12 + length
        if kind == b'IHDR':
            width, height, depth, color, _comp, _filt, interlace = struct.unpack('>IIBBBBB', chunk)
            if depth != 8 or color != 6 or interlace != 0:
                raise ValueError(f'{path}: only 8-bit RGBA non-interlaced PNG is supported '
                                 f'(depth={depth}, color={color}, interlace={interlace})')
        elif kind == b'IDAT':
            idat += chunk
        elif kind == b'IEND':
            break

    raw = zlib.decompress(bytes(idat))
    bpp = 4
    stride = width * bpp
    out = bytearray(height * stride)
    prev = bytearray(stride)
    src = 0
    for y in range(height):
        filter_type = raw[src]
        src += 1
        line = bytearray(raw[src:src + stride])
        src += stride
        for x in range(stride):
            a = line[x - bpp] if x >= bpp else 0
            b = prev[x]
            c = prev[x - bpp] if x >= bpp else 0
            if filter_type == 1:
                line[x] = (line[x] + a) & 0xFF
            elif filter_type == 2:
                line[x] = (line[x] + b) & 0xFF
            elif filter_type == 3:
                line[x] = (line[x] + ((a + b) >> 1)) & 0xFF
            elif filter_type == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                pred = a if pa <= pb and pa <= pc else (b if pb <= pc else c)
                line[x] = (line[x] + pred) & 0xFF
            elif filter_type != 0:
                raise ValueError(f'{path}: unknown PNG filter {filter_type}')
        out[y * stride:(y + 1) * stride] = line
        prev = line
    return width, height, bytes(out)


def c_array(name: str, payload: bytes) -> str:
    rows = []
    for i in range(0, len(payload), 20):
        rows.append('    ' + ','.join(str(b) for b in payload[i:i + 20]) + ',')
    body = '\n'.join(rows) if rows else '    0,'
    return f'static const unsigned char {name}[] = {{\n{body}\n}};\n'


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    assets_dir = Path(sys.argv[1])
    out_dir = Path(sys.argv[2])
    out_dir.mkdir(parents=True, exist_ok=True)

    images: list[tuple[str, int, int, bytes]] = []
    blobs: list[tuple[str, bytes]] = []
    for path in sorted(p for p in assets_dir.rglob('*') if p.is_file()):
        name = path.relative_to(assets_dir).with_suffix('').as_posix()
        ext = path.suffix.lower()
        if ext in IMAGE_EXTENSIONS:
            width, height, pixels = decode_png_rgba(path)
            images.append((name, width, height, pixels))
        elif ext in BLOB_EXTENSIONS:
            blobs.append((name, path.read_bytes()))

    header = '''/* Generated by tools/embed_assets.py. Do not edit. */
#ifndef ASSETS_DATA_H
#define ASSETS_DATA_H

#include <stddef.h>

typedef struct {
    const char *name;
    int width;
    int height;
    const unsigned char *rgba; /* width * height * 4 bytes, R G B A order */
} EmbeddedImage;

typedef struct {
    const char *name;
    size_t size;
    const unsigned char *data;
} EmbeddedBlob;

extern const EmbeddedImage embedded_images[];
extern const int embedded_image_count;
extern const EmbeddedBlob embedded_blobs[];
extern const int embedded_blob_count;

#endif
'''
    parts = ['/* Generated by tools/embed_assets.py. Do not edit. */\n',
             '#include "assets_data.h"\n\n']
    for i, (_name, _w, _h, pixels) in enumerate(images):
        parts.append(c_array(f'image_{i}', pixels))
    for i, (_name, payload) in enumerate(blobs):
        parts.append(c_array(f'blob_{i}', payload))

    parts.append('\nconst EmbeddedImage embedded_images[] = {\n')
    for i, (name, w, h, _pixels) in enumerate(images):
        parts.append(f'    {{"{name}", {w}, {h}, image_{i}}},\n')
    if not images:
        parts.append('    {NULL, 0, 0, NULL},\n')
    parts.append('};\n')
    parts.append(f'const int embedded_image_count = {len(images)};\n\n')

    parts.append('const EmbeddedBlob embedded_blobs[] = {\n')
    for i, (name, payload) in enumerate(blobs):
        parts.append(f'    {{"{name}", {len(payload)}, blob_{i}}},\n')
    if not blobs:
        parts.append('    {NULL, 0, NULL},\n')
    parts.append('};\n')
    parts.append(f'const int embedded_blob_count = {len(blobs)};\n')

    (out_dir / 'assets_data.h').write_text(header)
    (out_dir / 'assets_data.c').write_text(''.join(parts))
    print(f'embed_assets: {len(images)} image(s), {len(blobs)} blob(s) -> {out_dir}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
